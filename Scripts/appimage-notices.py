def debian_licenses(text):
    """License short names declared in a machine-readable copyright file, else None."""
    if not text.lstrip().startswith("Format:"):
        return None
    names = []
    for line in text.splitlines():
        if line.startswith("License:"):
            name = line[len("License:"):].strip()
            if name and name not in names:
                names.append(name)
    return names


def scan(appdir, dpkg, overrides):
    """Attribute every regular file in the AppDir. Returns (mapped, extra_files, own, errors)."""
    mapped, extra_files, own, errors, unowned = {}, {}, [], [], []
    forced = {}
    for entry in overrides["files"]:
        if bool(entry.get("package")) == bool(entry.get("extra")):
            die(f"'files' override needs exactly one of \"package\" or \"extra\": {entry}")
        forced[entry["path"]] = entry
    for dirpath, dirnames, filenames in os.walk(appdir):
        dirnames.sort()
        for filename in sorted(filenames):
            full = os.path.join(dirpath, filename)
            rel = os.path.relpath(full, appdir)
            if os.path.islink(full) or not os.path.isfile(full):
                continue
            if rel.startswith(("usr/share/doc/", "usr/share/common-licenses/")) or rel == ".DirIcon":
                continue
            if any(fnmatch.fnmatch(rel, entry["path"]) for entry in overrides["own"]):
                own.append(rel)
                continue
            force = next((entry for pattern, entry in forced.items() if fnmatch.fnmatch(rel, pattern)), None)
            if force:
                if force.get("package"):
                    mapped.setdefault(force["package"], []).append(rel)
                else:
                    extra_files.setdefault(force["extra"], []).append(rel)
                continue
            elf = is_elf(full)
            candidates = dpkg.candidates(filename)
            owners, how = [], ""
            if elf:
                bid = build_id(full)
                if bid:
                    owners = sorted({o for _, real, key in candidates if build_id(in_root(dpkg.root, real)) == bid
                                     for o in (dpkg.owners_of(real) or [key])})
                    how = "build-id"
            if not owners and candidates:
                digest = sha256(full)
                size = os.path.getsize(full)
                owners = sorted({o for _, real, key in candidates
                                 if os.path.getsize(in_root(dpkg.root, real)) == size
                                 and sha256(in_root(dpkg.root, real)) == digest
                                 for o in (dpkg.owners_of(real) or [key])})
                how = "content"
            if not owners and not elf:
                listed = "/" + rel
                if listed.startswith("/usr/"):
                    owners = dpkg.owners_of(resolve(dpkg.root, listed) or listed)
                    how = "path"
            if not owners and elf and candidates:
                best = max(suffix_len(rel, listed) for listed, _, _ in candidates)
                keys = sorted({o for listed, real, key in candidates if suffix_len(rel, listed) == best
                               for o in (dpkg.owners_of(real) or [key])})
                if len(keys) == 1:
                    owners, how = keys, "name"
                    warn(f"{rel}: matched {keys[0]} by file name only (build-id differs or is absent); "
                         f"check that the build host's package is the one that was bundled")
                else:
                    errors.append(f"{rel}: ambiguous owner {keys}; add a 'files' override naming the package")
                    continue
            if not owners:
                # A data file from outside dpkg (a font, icon set or sound) may carry CC-BY/OFL terms,
                # so it fails like an ELF file until an override says whose it is.
                unowned.append(f"{rel}: {'ELF' if elf else 'data'} file owned by no installed package")
                continue
            if len(owners) > 1:
                errors.append(f"{rel}: owned by several packages {owners}; add a 'files' override")
                continue
            mapped.setdefault(owners[0], []).append(rel)
    if unowned:
        errors += unowned + ["for each file above, add an 'own' override (the project's, or generated at build "
                             "time) or a 'files' override mapping it to an 'extra' component with its license "
                             "texts (third-party code, fonts, icons, sounds)"]
    return mapped, extra_files, own, errors


def annotate(appdir, package, overrides, base, root, template, runtime=None, report=None):
    appdir = os.path.abspath(appdir)
    if not os.path.isdir(os.path.join(appdir, "usr")):
        die(f"{appdir} has no usr/ directory; pass the AppDir root")
    dpkg = Dpkg(root)
    release = os_release(root)
    distro = release.get("ID", "")
    mapped, extra_files, own, errors = scan(appdir, dpkg, overrides)

    packages = []
    for key, files in sorted(mapped.items()):
        record = dpkg.record(key)
        name = record["name"]
        override = next((p for p in overrides["packages"] if p["package"] in (name, key)), None)
        if override and override.get("copyright_file"):
            text = read_text(base / override["copyright_file"], f"package override {name}")
        else:
            doc = resolve(root, f"/usr/share/doc/{name}/copyright")
            if not doc or not os.path.isfile(in_root(root, doc)):
                errors.append(f"{name}: no /usr/share/doc/{name}/copyright on the build host; add a 'packages' "
                              f"override with a copyright_file")
                continue
            text = read_text(in_root(root, doc), name)
        # A package from outside the distribution archive (a PPA or vendor repository) needs its own link.
        url = (override or {}).get("source_url") or source_url(template, distro, record["source"],
                                                               record["source_version"])
        packages.append({**record, "files": files, "text": text, "url": url})

    common = {}
    for pkg in packages:
        for ref in sorted(set(re.findall(r"/usr/share/common-licenses/([A-Za-z0-9][A-Za-z0-9.+_-]*)", pkg["text"]))):
            ref = ref.rstrip(".")
            path = resolve(root, f"/usr/share/common-licenses/{ref}")
            if not path or not os.path.isfile(in_root(root, path)):
                errors.append(f"{pkg['name']}: references /usr/share/common-licenses/{ref}, which the build host lacks")
                continue
            common[ref] = read_text(in_root(root, path), f"common license {ref}")

    values = {k: v for k, v in (runtime or {}).items() if isinstance(v, str)}
    if runtime and runtime.get("runtime_commit"):
        values["runtime_commit"] = runtime["runtime_commit"]
    extras = []
    for entry in overrides["extra"]:
        if entry.get("appimage_runtime") and not runtime:
            warn(f"extra '{entry['name']}' describes the AppImage runtime, which only 'appimage' mode can "
                 f"identify; skipped here")
            continue
        where = f"extra '{entry['name']}'"
        texts = [(Path(f).name, read_text(base / fill(f, values, where), where)) for f in entry.get("license_files", [])]
        if not texts:
            die(f"{where}: needs license_files")
        extras.append({"name": entry["name"], "version": fill(str(entry.get("version", "")), values, where),
                       "license": entry.get("license") or die(f"{where}: needs an SPDX \"license\""),
                       "url": fill(entry.get("source_url", ""), values, where),
                       "sources": [fill(s, values, where) for s in entry.get("sources", [])],
                       "files": extra_files.pop(entry["name"], []), "texts": texts,
                       "runtime": bool(entry.get("appimage_runtime"))})
    for name in extra_files:
        errors.append(f"'files' override points at unknown extra component '{name}'")
    if runtime and not any(e["runtime"] for e in extras):
        errors.append("the AppImage runtime statically links libfuse (LGPL-2.1), squashfuse, musl, zstd and zlib; "
                      "add an 'extra' entry with \"appimage_runtime\": true (see appimage-overrides.example.json)")
    if errors:
        for error in errors:
            print(f"appimage-notices: error: {error}", file=sys.stderr)
        sys.exit(1)

    built_on = (release.get("PRETTY_NAME") or " ".join(filter(None, (release.get("NAME"), release.get("VERSION_ID"))))
                or "the build host")
    docdir = os.path.join(appdir, "usr/share/doc", package)
    notices = os.path.join(docdir, "Third-Party-Notices.txt")
    existing = ""
    if os.path.exists(notices):
        existing = Path(notices).read_text(encoding="utf-8", errors="replace")
        if SECTION_MARKER in existing:
            die(f"{notices} already has the bundled-libraries section; run this once per AppDir")
    os.makedirs(docdir, exist_ok=True)
    for pkg in packages:
        target = os.path.join(appdir, "usr/share/doc", pkg["name"])
        if os.path.islink(target):
            os.unlink(target)
        os.makedirs(target, exist_ok=True)
        with open(os.path.join(target, "copyright"), "w", encoding="utf-8") as fh:
            fh.write(pkg["text"])
        os.chmod(os.path.join(target, "copyright"), 0o644)
    if common:
        licdir = os.path.join(appdir, "usr/share/common-licenses")
        os.makedirs(licdir, exist_ok=True)
        for ref, text in sorted(common.items()):
            with open(os.path.join(licdir, ref), "w", encoding="utf-8") as fh:
                fh.write(text)

    out = []
    if not existing:
        out.append(f"Third-party notices for the {package} AppImage\n")
    out.append(f"\n{RULE}\n{SECTION_MARKER}\n{RULE}\n"
               f"This AppImage bundles the libraries and data files below from {built_on}.\n"
               "Each entry names the distribution package and version, its source package,\n"
               "the licenses its copyright file declares, the bundled files, and that\n"
               "copyright file verbatim. SOURCES.txt next to this file links the exact\n"
               "source code. Referenced /usr/share/common-licenses texts follow the entries\n"
               "and also ship in usr/share/common-licenses/.\n")
    seen = {}
    for pkg in packages:
        declared = debian_licenses(pkg["text"])
        out.append(f"\n{THIN}\n{pkg['name']} {pkg['version']}\n"
                   f"Source package: {pkg['source']} {pkg['source_version']}\n"
                   f"License: {', '.join(declared) if declared else 'see the copyright text below'}\n"
                   f"Source: {pkg['url']}\n"
                   f"Files: {' '.join(pkg['files'])}\n\n")
        if pkg["text"] in seen:
            out.append(f"Copyright and license: identical to {seen[pkg['text']]} above.\n")
        else:
            seen[pkg["text"]] = pkg["name"]
            out.append(pkg["text"].rstrip("\n") + "\n")
    for ref, text in sorted(common.items()):
        out.append(f"\n{THIN}\n/usr/share/common-licenses/{ref}\n\n{text.rstrip()}\n")
    for extra in extras:
        out.append(f"\n{THIN}\n{extra['name']} {extra['version']}\nLicense: {extra['license']}\n")
        if extra["url"]:
            out.append(f"Source: {extra['url']}\n")
        if extra["runtime"]:
            out.append(f"Runtime SHA-256: {runtime['runtime_sha256']} ({runtime['runtime_size']} bytes, the "
                       f"AppImage's executable header, hashed with its digest and signature sections zeroed)\n")
            if runtime.get("license_blurb"):
                out.append("\nThe runtime states:\n" + runtime["license_blurb"].rstrip() + "\n")
        if extra["files"]:
            out.append(f"Files: {' '.join(extra['files'])}\n")
        for name, text in extra["texts"]:
            out.append(f"\n--- {name} ---\n{text.rstrip()}\n")
    with open(notices, "a", encoding="utf-8") as fh:
        fh.write("".join(out))

    by_source = {}
    for pkg in packages:
        entry = by_source.setdefault((pkg["source"], pkg["source_version"]), {"url": pkg["url"], "binaries": [], "copyleft": False})
        entry["binaries"].append(f"{pkg['name']} {pkg['version']}")
        entry["copyleft"] |= bool(COPYLEFT.search(pkg["text"]))
    lines = [f"Corresponding source for the third-party code in the {package} AppImage\n",
             f"{RULE}\n\nBuilt on: {built_on}\n",
             "One entry per distribution source package, with its exact version and a\n"
             "link to its source (the .dsc, upstream tarball and distribution patches).\n"
             "[copyleft] marks packages whose copyright file mentions the GPL, LGPL or\n"
             "MPL; it is a text match for convenience, and every package is listed.\n"]
    for (source, version), entry in sorted(by_source.items()):
        lines.append(f"\n{source} {version}{' [copyleft]' if entry['copyleft'] else ''}\n"
                     f"  Binary packages: {', '.join(sorted(entry['binaries']))}\n"
                     f"  Source: {entry['url']}\n"
                     f"  Fetch: apt-get source {source}={version}\n")
    if extras:
        lines.append(f"\nOther components\n{THIN}\n")
        for extra in extras:
            lines.append(f"\n{extra['name']} {extra['version']} ({extra['license']})\n")
            if extra["url"]:
                lines.append(f"  Source: {extra['url']}\n")
            for source in extra["sources"]:
                lines.append(f"  {source}\n")
    with open(os.path.join(docdir, "SOURCES.txt"), "w", encoding="utf-8") as fh:
        fh.write("".join(lines))

    summary = {"packages": len(packages), "source_packages": len(by_source), "common_licenses": sorted(common),
               "extras": [e["name"] for e in extras], "own": own}
    if report:
        with open(report, "w", encoding="utf-8") as fh:
            json.dump({**summary, "files": {p["name"]: p["files"] for p in packages}}, fh, indent=1, sort_keys=True)
    print(f"appimage-notices: {len(packages)} packages from {len(by_source)} source packages, "
          f"{len(common)} common licenses, {len(extras)} extra components; "
          f"{len(own)} project files")
    return summary


