# ---------------------------------------------------------------- ELF helpers

def elf_header(data):
    """Return (is64, endian) for ELF data, or None."""
    if len(data) < 64 or data[:4] != b"\x7fELF":
        return None
    return data[4] == 2, "<" if data[5] == 1 else ">"


def elf_end(data):
    """End of the ELF image, where an AppImage's squashfs starts.

    Like the AppImage runtime's own computation: the later of the section header
    table's end and the end of the last section's data.
    """
    hdr = elf_header(data)
    if not hdr:
        die("not an ELF file (an AppImage starts with its ELF runtime)")
    is64, e = hdr
    if is64:
        shoff = struct.unpack_from(e + "Q", data, 0x28)[0]
        shentsize, shnum = struct.unpack_from(e + "HH", data, 0x3A)
        last_off, last_size = struct.unpack_from(e + "QQ", data, shoff + shentsize * (shnum - 1) + 24)
    else:
        shoff = struct.unpack_from(e + "I", data, 0x20)[0]
        shentsize, shnum = struct.unpack_from(e + "HH", data, 0x2E)
        last_off, last_size = struct.unpack_from(e + "II", data, shoff + shentsize * (shnum - 1) + 16)
    return max(shoff + shentsize * shnum, last_off + last_size)


def elf_sections(data):
    """Map section name -> (offset, size)."""
    is64, e = elf_header(data)
    if is64:
        shoff = struct.unpack_from(e + "Q", data, 0x28)[0]
        shentsize, shnum, shstrndx = struct.unpack_from(e + "HHH", data, 0x3A)
        fmt = e + "IIQQQQ"
    else:
        shoff = struct.unpack_from(e + "I", data, 0x20)[0]
        shentsize, shnum, shstrndx = struct.unpack_from(e + "HHH", data, 0x2E)
        fmt = e + "IIIIII"
    raw = []
    for i in range(shnum):
        name, _type, _flags, _addr, off, size = struct.unpack_from(fmt, data, shoff + i * shentsize)
        raw.append((name, off, size))
    stroff = raw[shstrndx][1]
    result = {}
    for name, off, size in raw:
        end = data.index(b"\0", stroff + name)
        result[data[stroff + name:end].decode("ascii", "replace")] = (off, size)
    return result


def build_id(path):
    """GNU build-id of an ELF file (hex), read from its PT_NOTE segments; None if absent."""
    try:
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError:
        return None
    hdr = elf_header(data)
    if not hdr:
        return None
    is64, e = hdr
    try:
        if is64:
            phoff = struct.unpack_from(e + "Q", data, 0x20)[0]
            phentsize, phnum = struct.unpack_from(e + "HH", data, 0x36)
        else:
            phoff = struct.unpack_from(e + "I", data, 0x1C)[0]
            phentsize, phnum = struct.unpack_from(e + "HH", data, 0x2A)
        for i in range(phnum):
            base = phoff + i * phentsize
            p_type = struct.unpack_from(e + "I", data, base)[0]
            if p_type != 4:  # PT_NOTE
                continue
            if is64:
                offset, filesz = struct.unpack_from(e + "Q", data, base + 8)[0], struct.unpack_from(e + "Q", data, base + 32)[0]
            else:
                offset, filesz = struct.unpack_from(e + "I", data, base + 4)[0], struct.unpack_from(e + "I", data, base + 16)[0]
            pos, end = offset, offset + filesz
            while pos + 12 <= end:
                namesz, descsz, ntype = struct.unpack_from(e + "III", data, pos)
                name_start = pos + 12
                desc_start = name_start + ((namesz + 3) & ~3)
                if ntype == 3 and data[name_start:name_start + namesz].rstrip(b"\0") == b"GNU":
                    return data[desc_start:desc_start + descsz].hex()
                pos = desc_start + ((descsz + 3) & ~3)
    except struct.error:
        return None
    return None


def is_elf(path):
    try:
        with open(path, "rb") as fh:
            return fh.read(4) == b"\x7fELF"
    except OSError:
        return False


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


# --------------------------------------------------------- AppImage runtime

def runtime_info(path):
    """Identify an AppImage's runtime and the versions of what it statically links."""
    with open(path, "rb") as fh:
        data = fh.read()
    offset = elf_end(data)
    if data[offset:offset + 4] != b"hsqs":
        die(f"{path}: no squashfs at offset {offset}; only type 2 AppImages are supported")
    runtime = data[:offset]
    sections = elf_sections(runtime)
    info = {"offset": offset, "runtime_size": offset, "signed": False}
    if ".sha256_sig" in sections:
        off, size = sections[".sha256_sig"]
        info["signed"] = bool(data[off:off + size].strip(b"\0"))
    # Identify the runtime build itself: zero the per-file digest, signature and key.
    canonical = bytearray(runtime)
    for name in (".digest_md5", ".sha256_sig", ".sig_key"):
        if name in sections:
            off, size = sections[name]
            canonical[off:off + size] = b"\0" * size
    info["runtime_sha256"] = hashlib.sha256(canonical).hexdigest()

    def find(pattern):
        match = re.search(pattern, runtime)
        return match.group(1).decode() if match else None

    # Versions are read only next to strings that identify their library (libfuse's "FUSE
    # library version", zstd's first error string); otherwise they stay unset, and an override
    # that uses the placeholder fails instead of pinning another library's version.
    info["runtime_commit"] = find(rb"type2-runtime/commit/([0-9a-f]{7,40})")
    info["libfuse_version"] = find(rb"\x00(3\.\d+\.\d+)\x00FUSE library version")
    info["squashfuse_version"] = find(rb"squashfuse (\d+\.\d+\.\d+)")
    info["zstd_version"] = find(rb"\x00(1\.\d+\.\d+)\x00No error detected\x00")
    info["zlib_version"] = find(rb"inflate (\d+\.\d+(?:\.\d+)*) Copyright")
    start = runtime.find(b"License:\n  This executable contains code from")
    info["license_blurb"] = (runtime[start:runtime.index(b"\0", start)].decode("utf-8", "replace")
                             if start >= 0 else None)
    return info


def appimage_digest_md5(data, sections, chunk=4096):
    """Recompute .digest_md5 exactly as appimagetool's appimage_type2_digest_md5 does.

    appimagetool hashes whole 4 KiB buffers and skips the digest, signature and
    key sections by leaving the previous buffer contents in place; this emulates
    that byte for byte so the stored digest stays valid after a repack.
    """
    skip = [sections[name] for name in (".digest_md5", ".sha256_sig", ".sig_key") if name in sections]
    fp = io.BytesIO(data)
    buf = bytearray(chunk)
    md5 = hashlib.md5()
    bytes_left = len(data)
    skip_following = 0
    wrap = 1 << 64
    while bytes_left > 0:
        current = fp.tell()
        left = chunk
        if skip_following > 0:
            step = chunk if skip_following % chunk == 0 else skip_following % chunk
            left -= step
            skip_following -= step
            fp.seek(step, 1)
        for off, length in skip:
            distance = (off - current) % wrap
            if off and length and 0 < distance < chunk:
                begin = distance % chunk
                read = fp.read(begin)
                buf[0:len(read)] = read
                left -= begin + length
                if left < 0:
                    skip_following = -left
                    left = 0
                fp.seek(chunk - left - begin, 1)
        if left > 0:
            read = fp.read(left)
            buf[chunk - left:chunk - left + len(read)] = read
        md5.update(bytes(buf))
        bytes_left -= chunk
    return md5.digest()


# --------------------------------------------------------------- dpkg data

def resolve(root, path):
    """Resolve symlinks in an absolute path inside root (absolute link targets stay in root)."""
    pending = [p for p in path.split("/") if p and p != "."]
    done = []
    hops = 0
    while pending:
        part = pending.pop(0)
        if part == "..":
            if done:
                done.pop()
            continue
        full = os.path.join(root, *done, part)
        if os.path.islink(full):
            hops += 1
            if hops > 40:
                return None
            target = os.readlink(full)
            if target.startswith("/"):
                done = []
            pending = [p for p in target.split("/") if p and p != "."] + pending
            continue
        done.append(part)
    return "/" + "/".join(done)


def in_root(root, path):
    return os.path.join(root, path.lstrip("/"))


class Dpkg:
    """Installed packages, their file lists and versions, read from dpkg's database."""

    def __init__(self, root):
        self.root = root
        admin = in_root(root, "/var/lib/dpkg")
        if not os.path.isfile(os.path.join(admin, "status")):
            die(f"no dpkg database under {admin}; run this on the Debian/Ubuntu host that built the AppImage")
        self.packages = {}
        with open(os.path.join(admin, "status"), encoding="utf-8", errors="replace") as fh:
            for stanza in fh.read().split("\n\n"):
                fields = {}
                for line in stanza.splitlines():
                    if line[:1] in (" ", "\t") or ":" not in line:
                        continue
                    key, value = line.split(":", 1)
                    fields[key] = value.strip()
                if "Package" not in fields or "installed" not in fields.get("Status", "").split():
                    continue
                name, arch = fields["Package"], fields.get("Architecture", "")
                source, source_version = fields["Package"], fields.get("Version", "")
                if "Source" in fields:
                    match = re.match(r"(\S+)(?:\s+\((\S+)\))?", fields["Source"])
                    source = match.group(1)
                    source_version = match.group(2) or fields.get("Version", "")
                record = {"name": name, "arch": arch, "version": fields.get("Version", ""),
                          "source": source, "source_version": source_version}
                self.packages[name] = record
                self.packages[f"{name}:{arch}"] = record
        self.by_basename = {}
        for listing in Path(admin, "info").glob("*.list"):
            key = listing.name[:-len(".list")]
            if key not in self.packages and key.split(":")[0] not in self.packages:
                continue  # removed package whose file list remains (config-files state)
            with open(listing, encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    path = line.rstrip("\n")
                    if path and path != "/.":
                        self.by_basename.setdefault(os.path.basename(path), []).append((path, key))
        self._owners = {}

    def record(self, key):
        record = self.packages.get(key) or self.packages.get(key.split(":")[0])
        if not record:
            die(f"package {key} has a file list but no installed status entry")
        return record

    def candidates(self, basename):
        """Host files with this basename: list of (listed path, resolved path, package key)."""
        result = []
        for listed, key in self.by_basename.get(basename, []):
            real = resolve(self.root, listed)
            if real and os.path.isfile(in_root(self.root, real)):
                result.append((listed, real, key))
        return result

    def owners_of(self, real):
        """Packages whose file list contains a path that resolves to `real`."""
        if real not in self._owners:
            self._owners[real] = sorted({key for listed, key in self.by_basename.get(os.path.basename(real), [])
                                         if resolve(self.root, listed) == real})
        return self._owners[real]


def suffix_len(a, b):
    a, b = a.strip("/").split("/"), b.strip("/").split("/")
    n = 0
    while n < min(len(a), len(b)) and a[-1 - n] == b[-1 - n]:
        n += 1
    return n


def os_release(root):
    info = {}
    path = in_root(root, "/etc/os-release")
    if not os.path.exists(path):
        path = in_root(root, "/usr/lib/os-release")
    try:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                if "=" in line:
                    key, value = line.rstrip("\n").split("=", 1)
                    info[key] = value.strip('"')
    except OSError:
        pass
    return info


def source_url(template, distro, source, version):
    quoted = urllib.parse.quote(version, safe=":~+")
    if template:
        return template.format(source=source, version=quoted)
    if distro == "ubuntu":
        return f"https://launchpad.net/ubuntu/+source/{source}/{quoted}"
    if distro == "debian":
        return f"https://snapshot.debian.org/package/{source}/{quoted}/"
    die(f"unknown distribution '{distro}': pass --source-url 'https://.../{{source}}/{{version}}'")


# --------------------------------------------------------------- overrides

def load_overrides(path):
    if not path:
        return {"own": [], "files": [], "packages": [], "extra": []}, Path.cwd()
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    unknown = set(data) - {"own", "files", "packages", "extra", "_comment"}
    if unknown:
        die(f"{path}: unknown keys {sorted(unknown)}")
    required = {"own": ("path",), "files": ("path",), "packages": ("package",), "extra": ("name",)}
    for kind in ("own", "files", "packages", "extra"):
        data.setdefault(kind, [])
        for entry in data[kind]:
            if not isinstance(entry, dict):
                die(f"{path}: '{kind}' entries must be objects: {entry!r}")
            if not str(entry.get("reason", "")).strip():
                die(f"{path}: every '{kind}' override needs a non-empty \"reason\": {entry}")
            for key in required[kind]:
                if not str(entry.get(key, "")).strip():
                    die(f"{path}: '{kind}' override needs \"{key}\": {entry}")
    return data, Path(path).resolve().parent


def fill(text, values, where):
    def replace(match):
        value = values.get(match.group(1))
        if not value:
            die(f"{where}: cannot fill {{{match.group(1)}}} (only known in 'appimage' mode, "
                f"or not detected in this runtime)")
        return value
    return PLACEHOLDER.sub(replace, text)


def read_text(path, where):
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError as error:
        die(f"{where}: cannot read {path}: {error}")
    if not text.strip():
        die(f"{where}: {path} is empty")
    return text


