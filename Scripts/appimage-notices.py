def squashfs_params(path, offset):
    out = run(["unsquashfs", "-s", "-o", str(offset), path]).stdout
    comp = re.search(r"Compression (\w+)", out)
    block = re.search(r"Block size (\d+)", out)
    if not comp or not block:
        die(f"cannot read squashfs parameters of {path}:\n{out}")
    return comp.group(1), block.group(1)


def run(cmd, **kwargs):
    try:
        return subprocess.run(cmd, check=True, capture_output=True, text=True, **kwargs)
    except FileNotFoundError:
        die(f"{cmd[0]} not found; install squashfs-tools")
    except subprocess.CalledProcessError as error:
        die(f"{' '.join(cmd)} failed:\n{error.stdout}{error.stderr}")


def repack(path, args, overrides, base):
    info = runtime_info(path)
    if info["signed"]:
        die(f"{path} carries an AppImage signature, which a repack invalidates; sign after this step")
    comp, block = squashfs_params(path, info["offset"])
    work = tempfile.mkdtemp(prefix="appimage-notices-", dir=args.workdir)
    try:
        root = os.path.join(work, "squashfs-root")
        run(["unsquashfs", "-n", "-no-xattrs", "-d", root, "-o", str(info["offset"]), path])
        annotate(root, args.package, overrides, base, args.root, args.source_url, runtime=info, report=args.report)
        fs = os.path.join(work, "fs.squashfs")
        run(["mksquashfs", root, fs, "-root-owned", "-noappend", "-no-xattrs", "-no-progress",
             "-comp", comp, "-b", block, "-mkfs-time", "0", "-all-time", "0"])
        with open(path, "rb") as fh:
            runtime = bytearray(fh.read(info["offset"]))
        data = bytearray(runtime + Path(fs).read_bytes())
        sections = elf_sections(bytes(runtime))
        if ".digest_md5" in sections:
            off, size = sections[".digest_md5"]
            if size < 16:
                die(f".digest_md5 is {size} bytes; expected at least 16")
            data[off:off + size] = b"\0" * size
            data[off:off + 16] = appimage_digest_md5(bytes(data), sections)
        tmp = path + ".notices-tmp"
        with open(tmp, "wb") as fh:
            fh.write(data)
        os.chmod(tmp, os.stat(path).st_mode | 0o111)
        os.replace(tmp, path)
    finally:
        if not args.keep_workdir:
            shutil.rmtree(work, ignore_errors=True)
    print(f"appimage-notices: repacked {path} (runtime {info['runtime_commit'] or 'unknown'}, {comp}, block {block})")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="mode", required=True)
    for mode in ("appimage", "appdir"):
        p = sub.add_parser(mode)
        p.add_argument("target", help="the .AppImage file" if mode == "appimage" else "the AppDir root")
        p.add_argument("--package", required=True, help="doc directory name, e.g. the deb package name")
        p.add_argument("--overrides", help="JSON overrides (own files, forced owners, extra components)")
        p.add_argument("--root", default="/", help="root of the build host's file system (default /)")
        p.add_argument("--source-url", help="source link template with {source} and {version}")
        p.add_argument("--report", help="write a JSON report of the attribution")
        if mode == "appimage":
            p.add_argument("--workdir", help="parent directory for the temporary extraction")
            p.add_argument("--keep-workdir", action="store_true")
    p = sub.add_parser("runtime-info")
    p.add_argument("target")
    args = parser.parse_args()

    if args.mode == "runtime-info":
        json.dump(runtime_info(args.target), sys.stdout, indent=1)
        print()
        return
    overrides, base = load_overrides(args.overrides)
    if args.mode == "appdir":
        annotate(args.target, args.package, overrides, base, args.root, args.source_url, report=args.report)
    else:
        repack(os.path.abspath(args.target), args, overrides, base)


if __name__ == "__main__":
    main()
