#!/usr/bin/env python3
"""Add license notices and source pointers for the system libraries in an AppImage.

linuxdeploy (used directly or through Tauri) copies shared libraries, plugins
and data files from the build host into the AppDir. Each of them comes from a
Debian/Ubuntu package whose /usr/share/doc/<pkg>/copyright carries the
license and copyright notices, and many are LGPL/GPL, which also need exact
source pointers. This script:

  * maps every regular file in the AppDir to the host package that owns it
    (ELF files by GNU build-id, data files by content hash, with file-name
    fallbacks), and fails when a bundled file cannot be attributed;
  * copies each owning package's copyright file to usr/share/doc/<pkg>/copyright
    and the /usr/share/common-licenses texts they reference to
    usr/share/common-licenses/;
  * appends a "Bundled system libraries" section to
    usr/share/doc/<package>/Third-Party-Notices.txt (created if absent);
  * writes usr/share/doc/<package>/SOURCES.txt with each source package's exact
    name, version and source link (Launchpad for Ubuntu, snapshot.debian.org
    for Debian);
  * in "appimage" mode, also identifies the AppImage runtime (the ELF header
    outside the squashfs, which statically links LGPL libfuse) and repacks the
    AppImage with the same runtime, compression and block size.

Usage:
  appimage-notices.py appimage FILE.AppImage --package NAME --overrides FILE
  appimage-notices.py appdir APPDIR --package NAME [--overrides FILE]
  appimage-notices.py runtime-info FILE.AppImage

Run it on the machine that built the AppImage (same packages installed).
Overrides are JSON; every entry needs a non-empty "reason". See
appimage-overrides.example.json. Requires Python 3.8+, dpkg's database, and
unsquashfs/mksquashfs (squashfs-tools) for the appimage mode.
"""

